package grpccodegen

import (
	"fmt"
	"path/filepath"

	"github.com/blueprint-uservices/blueprint/plugins/golang"
	"github.com/blueprint-uservices/blueprint/plugins/golang/gocode"
	"github.com/blueprint-uservices/blueprint/plugins/golang/gogen"
	"golang.org/x/exp/slog"
)

/*
This function is used by the GRPC plugin to generate the server-side GRPC service.

It is assumed that outputPackage is the same as the one where the .proto is generated to
*/
func GenerateServerHandler(builder golang.ModuleBuilder, service *gocode.ServiceInterface, outputPackage string) error {
	pkg, err := builder.CreatePackage(outputPackage)
	if err != nil {
		return err
	}

	server := &serverArgs{
		Package: pkg,
		Service: service,
		Name:    service.BaseName + "_GRPCServerHandler",
		Imports: gogen.NewImports(pkg.Name),
	}

	server.Imports.AddPackages(
		"context", "net", "os", "strconv",
		"google.golang.org/grpc",
	)

	slog.Info(fmt.Sprintf("Generating %v/%v_GRPCServer.go", server.Package.PackageName, service.Name))
	outputFile := filepath.Join(server.Package.Path, service.Name+"_GRPCServer.go")
	return gogen.ExecuteTemplateToFile("GRPCServer", serverTemplate, server, outputFile)
}

/*
Arguments to the template code
*/
type serverArgs struct {
	Package golang.PackageInfo
	Service *gocode.ServiceInterface
	Name    string         // Name of the generated wrapper class
	Imports *gogen.Imports // Manages imports for us
}

var serverTemplate = `// Blueprint: Auto-generated by GRPC Plugin
package {{.Package.ShortName}}

{{.Imports}}

type {{.Name}} struct {
	Unimplemented{{.Service.Name}}Server
	Service {{.Imports.NameOf .Service.UserType}}
	Address string
}

func New_{{.Name}}(ctx context.Context, service {{.Imports.NameOf .Service.UserType}}, serverAddress string) (*{{.Name}}, error) {
	handler := &{{.Name}}{}
	handler.Service = service
	handler.Address = serverAddress
	return handler, nil
}

// Blueprint: Run is called automatically in a separate goroutine by runtime/plugins/golang/di.go
func (handler *{{.Name}}) Run(ctx context.Context) error {
	lis, err := net.Listen("tcp", handler.Address)
	if err != nil {
		return err
	}

	// MaxConcurrentStreams MUST be set explicitly.
	//
	// grpc-go's client starts with streamQuota = defaultMaxStreamsClient = 100
	// (internal/transport/defaults.go) and only raises it when it RECEIVES a
	// SETTINGS_MAX_CONCURRENT_STREAMS frame. But the server only SENDS that
	// setting when its value differs from math.MaxUint32 (internal/transport/
	// http2_server.go), and MaxUint32 is the default. So a plain
	// grpc.NewServer() advertises nothing and every client is silently pinned
	// to 100 concurrent in-flight RPCs per connection; extra calls queue
	// client-side (see https://grpc.io/docs/guides/performance/). That caps a
	// service at 100/RTT rps. It does NOT bind a fast service (payloadbench
	// needs only ~19 concurrent streams) but DOES bind slower ones: dsb_sn at
	// ~30ms per call needs 150-300 streams at 5-10k rps.
	//
	// Override with GRPC_MAX_CONCURRENT_STREAMS; 0 restores grpc-go's
	// (counter-intuitively limiting) default behaviour.
	maxStreams := uint32(8192)
	if v := os.Getenv("GRPC_MAX_CONCURRENT_STREAMS"); v != "" {
		if n, err := strconv.ParseUint(v, 10, 32); err == nil {
			maxStreams = uint32(n)
		}
	}
	var opts []grpc.ServerOption
	if maxStreams > 0 {
		opts = append(opts, grpc.MaxConcurrentStreams(maxStreams))
	}
	s := grpc.NewServer(opts...)
	Register{{.Service.Name}}Server(s, handler)

	go func() {
		select {
		case <-ctx.Done():
			s.GracefulStop()
		}
	}()

	return s.Serve(lis)
}

{{$service := .Service.Name -}}
{{$receiver := .Name -}}
{{ range $_, $f := .Service.Methods }}
func (handler *{{$receiver}}) {{$f.Name -}}
		(ctx context.Context, req *{{$service}}_{{$f.Name}}_Request) (*{{$service}}_{{$f.Name}}_Response, error) {
	{{ArgVarsEquals $f}} req.unmarshall()
	{{RetVars $f "err"}} := handler.Service.{{$f.Name}}({{ArgVars $f "ctx"}})
	if err != nil {
		return nil, err
	}

	rsp := &{{$service}}_{{$f.Name}}_Response{}
	rsp.marshall({{RetVars $f}})
	return rsp, nil
}
{{end}}
`
