#!/usr/bin/env python3
"""Tomislav-RetCtx: build every prepared app image and pin all deployed digests.

Build failures stop the campaign. Existing backend images are reused from the
saved live deployment; application source is generated by the existing wiring.
"""
import argparse
import hashlib
import json
import os
from pathlib import Path
import re
import subprocess
import urllib.request

import yaml

from prepare_dsb_sn_e2e import command, write_json, REGISTRY


def registry_digest(image):
    if '@sha256:' in image:
        return image
    assert image.startswith(REGISTRY + '/'), image
    repository, tag = image[len(REGISTRY) + 1:].rsplit(':', 1)
    accept = ', '.join(('application/vnd.docker.distribution.manifest.v2+json',
                        'application/vnd.docker.distribution.manifest.list.v2+json',
                        'application/vnd.oci.image.manifest.v1+json',
                        'application/vnd.oci.image.index.v1+json'))
    request = urllib.request.Request(f'http://{REGISTRY}/v2/{repository}/manifests/{tag}',
                                     headers={'Accept': accept})
    with urllib.request.build_opener(urllib.request.ProxyHandler({})).open(request, timeout=30) as response:
        digest = response.headers['Docker-Content-Digest']
    assert digest and digest.startswith('sha256:'), image
    return f'{REGISTRY}/{repository}@{digest}'


def local_base_digest(image):
    result = subprocess.run(['docker', 'image', 'inspect', image], capture_output=True, text=True)
    if result.returncode:
        command(['docker', 'pull', image])
        result = command(['docker', 'image', 'inspect', image], capture_output=True, text=True)
    info = json.loads(result.stdout)[0]
    assert info['RepoDigests'], image
    return info['RepoDigests'][0]


def prepare_dockerfile(path, bases):
    text = path.read_text()
    text = text.replace('RUN go mod download',
        'RUN --mount=type=cache,id=dsb-sn-gomod,target=/go/pkg/mod go mod download')
    text = text.replace('RUN go build ',
        'RUN --mount=type=cache,id=dsb-sn-gomod,target=/go/pkg/mod '
        '--mount=type=cache,id=dsb-sn-gobuild,target=/root/.cache/go-build go build ')
    for match in list(re.finditer(r'(?m)^FROM ([^\s]+)', text)):
        image = match[1]
        if '@sha256:' in image:
            continue
        if image not in bases:
            bases[image] = local_base_digest(image)
        text = text.replace('FROM ' + image, 'FROM ' + bases[image])
    for match in list(re.finditer(r'COPY --from=(busybox:[^\s]+)', text)):
        image = match[1]
        if '@sha256:' in image:
            continue
        if image not in bases:
            bases[image] = local_base_digest(image)
        text = text.replace('COPY --from=' + image, 'COPY --from=' + bases[image])
    marker = '# Tomislav-RetCtx: frozen base digests and shared Go compilation caches.\n'
    if marker not in text:
        text = text.replace('# syntax=docker/dockerfile:1\n', '# syntax=docker/dockerfile:1\n' + marker)
    path.write_text(text)


def tree_hash(context):
    digest = hashlib.sha256()
    for path in sorted(context.rglob('*')):
        if path.is_file():
            digest.update(str(path.relative_to(context)).encode() + b'\0')
            digest.update(hashlib.sha256(path.read_bytes()).digest())
    return digest.hexdigest()


def build(root):
    assert json.loads((root / 'prepare-status.json').read_text())['state'] == 'complete'
    cases = json.loads((root / 'cases.json').read_text())
    previous = json.loads((root / 'before/deployments.json').read_text())['items']
    backends = {}
    for doc in previous:
        name = doc['metadata']['name']
        if '-service-' not in name:
            base = re.sub(r'-(?:cgpb|pb|sb|v)-es.*-ctr$', '', name)
            backends[base] = registry_digest(doc['spec']['template']['spec']['containers'][0]['image'])
    bases_path = root / 'base-image-digests.json'
    bases = json.loads(bases_path.read_text()) if bases_path.exists() else {}
    completed = 0
    for case in cases:
        kind, variant = case['kind'], case['variant']
        directory = Path(case['case'])
        manifest = directory / 'manifest.yaml'
        documents = list(yaml.safe_load_all(manifest.read_text()))
        compose_dir = Path(case['build']) / 'docker'
        compose = yaml.safe_load((compose_dir / 'docker-compose.yml').read_text())
        images_path = directory / 'images.json'
        images = json.loads(images_path.read_text()) if images_path.exists() else {}
        app_count = 0
        for doc in documents:
            if doc['kind'] not in ('Deployment', 'DaemonSet'):
                continue
            name = doc['metadata']['name']
            for container in doc['spec']['template']['spec']['containers']:
                if name.startswith('otelcol-'):
                    assert '@sha256:' in container['image']
                elif '-service-' not in name:
                    base = name.removesuffix('-' + variant + '-ctr')
                    container['image'] = backends[base]
                else:
                    app_count += 1
                    service = next(s for s in compose['services'] if s.replace('_', '-') == name)
                    configuration = compose['services'][service]
                    context = configuration['build']
                    if isinstance(context, dict):
                        context = context['context']
                    context = compose_dir / context
                    prepare_dockerfile(context / 'Dockerfile', bases)
                    write_json(bases_path, bases)
                    digest = tree_hash(context)
                    if name not in images:
                        image = f'{REGISTRY}/{name}:latest'
                        write_json(root / 'image-build-status.json', {
                            'state': 'running', 'kind': kind, 'service': name,
                            'completed_app_images': completed, 'total_app_images': 13 * len(cases)})
                        with (root / 'logs' / f'build-{name}.log').open('w') as log:
                            command(['docker', 'build', '--progress=plain', '-t', image, context],
                                    env=dict(os.environ, DOCKER_BUILDKIT='1'), stdout=log, stderr=subprocess.STDOUT)
                            command(['docker', 'push', image], stdout=log, stderr=subprocess.STDOUT)
                        frozen = registry_digest(image)
                        info = json.loads(command(['docker', 'image', 'inspect', image],
                                                   capture_output=True, text=True).stdout)[0]
                        assert frozen in info['RepoDigests']
                        images[name] = {'image': frozen, 'image_id': info['Id'], 'context_sha256': digest}
                        write_json(images_path, images)
                    assert images[name]['context_sha256'] == digest, f'build context changed: {name}'
                    container['image'] = images[name]['image']
                    completed += 1
                container['imagePullPolicy'] = 'IfNotPresent'
        assert app_count == 13, (kind, app_count)
        manifest.write_text(yaml.safe_dump_all(documents, sort_keys=False))
        assert all('@sha256:' in c['image'] for d in documents
                   if d['kind'] in ('Deployment', 'DaemonSet')
                   for c in d['spec']['template']['spec']['containers'])
        write_json(directory / 'build-complete.json', {
            'app_images': app_count, 'manifest_sha256': hashlib.sha256(manifest.read_bytes()).hexdigest()})
    write_json(root / 'image-build-status.json', {'state': 'complete', 'app_images': completed})


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--out', type=Path, required=True)
    args = parser.parse_args()
    try:
        build(args.out.resolve())
    except Exception as error:
        write_json(args.out / 'image-build-status.json', {'state': 'failed', 'error': str(error)})
        raise
